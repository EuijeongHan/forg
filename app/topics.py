"""시장 전체 유형 구독 (topic subscription).

워치리스트는 '어느 기업'을 보는지이고, 토픽은 '어떤 유형'을 기업과 무관하게
보는지다. 첫 사용자(반도체 애널리스트)의 요청에서 나왔다 — 공급계약은 커버리지
밖 기업 건이라도 밸류체인 신호라서, 등록 여부와 상관없이 봐야 한다는 것.

모두에게 보내지 않고 구독한 사람에게만 보낸다. 하루 평균 18건은 원하는 사람에겐
핵심 정보지만 원치 않는 사람에겐 소음이다.
"""

TOPICS: dict[str, dict] = {
    "공급계약": {
        "label": "단일판매·공급계약체결",
        # 보고서명 실측(2026-08-26, 10영업일 179건): '단일판매ㆍ공급계약체결',
        # '[기재정정]…', '…(자율공시)', '…(자회사의 주요경영사항)' 형태가 섞인다.
        # 가운뎃점이 'ㆍ'(U+318D)라 이름 전체로 매칭하면 놓친다 — 조각으로 본다.
        "patterns": ("단일판매", "공급계약"),
        "desc": "매출 대비 일정 비율 이상 계약 체결 시 공시 (상장사 하루 평균 18건, 정정 포함)",
    },
}


def match_topic(report_nm: str) -> str | None:
    """공시명이 구독 가능한 토픽에 해당하면 그 키를 돌려준다."""
    for key, spec in TOPICS.items():
        if any(p in report_nm for p in spec["patterns"]):
            return key
    return None
