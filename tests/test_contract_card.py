# ── 💡 코멘트 가드 ───────────────────────────────────────────────────
async def _comment(text):
    async def fake(prompt):
        return text
    orig = summarizer._generate_with_fallback
    summarizer._generate_with_fallback = fake
    try:
        return await summarizer._append_ai_comment(
            "[카드]\n• 계약금액: 105,306,300,000원", "p",
            {"content": "계약금액 105,306,300,000 최근매출액 305,653,861,102"})
    finally:
        summarizer._generate_with_fallback = orig


